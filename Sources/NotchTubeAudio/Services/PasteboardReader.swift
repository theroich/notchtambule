import AppKit
import Foundation

/// Pasteboard UTI / type identifiers used to recognize confidential, transient,
/// or self-generated clipboard writes.
enum PasteboardMarkerType {
    /// Standard NSPasteboard marker for sensitive data (passwords, tokens).
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    /// Standard NSPasteboard marker for temporary/transient clipboard mutations.
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    /// Standard NSPasteboard marker for automatically generated content.
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// 1Password specific confidential marker.
    static let onePassword = NSPasteboard.PasteboardType("com.agilebits.onepassword")
    /// Internal marker set when NotchTubeAudio writes an item back to the system pasteboard.
    static let internalCaptureIgnore = NSPasteboard.PasteboardType("com.notchtubeaudio.pasteboard.internal")

    /// Default set of confidential/transient pasteboard types that should not be recorded.
    static let confidentialTypes: Set<NSPasteboard.PasteboardType> = [
        concealed,
        transient,
        autoGenerated,
        onePassword
    ]
}

/// Abstraction over `NSPasteboard` and `NSWorkspace` to enable deterministic unit testing
/// without mutating or reading the real macOS system pasteboard.
@MainActor
protocol PasteboardReading: AnyObject {
    /// Monotonically increasing change counter from the underlying pasteboard.
    var changeCount: Int { get }

    /// All pasteboard types present in the current pasteboard snapshot.
    var types: [NSPasteboard.PasteboardType] { get }

    /// Reads file URLs (`isFileURL == true`) currently on the pasteboard.
    func readFileURLs() -> [URL]

    /// Reads raw data for the specified pasteboard type (e.g. `.png` or `.tiff`).
    func data(forType dataType: NSPasteboard.PasteboardType) -> Data?

    /// Reads a plain string for the specified pasteboard type (typically `.string`).
    func string(forType dataType: NSPasteboard.PasteboardType) -> String?

    /// Metadata of the application that is currently frontmost when the copy occurred.
    func frontmostSourceApp() -> ClipboardSourceApp?

    /// Writes a `ClipboardPayload` back to the pasteboard, tagging the change with
    /// ``PasteboardMarkerType/internalCaptureIgnore`` and returning the new `changeCount`.
    @discardableResult
    func write(_ payload: ClipboardPayload) -> Int
}

extension PasteboardReading {
    @discardableResult
    func write(_ payload: ClipboardPayload) -> Int {
        changeCount
    }
}

/// Production implementation backed by `NSPasteboard.general` and `NSWorkspace.shared`.
@MainActor
final class SystemPasteboardReader: PasteboardReading {
    private let pasteboard: NSPasteboard
    private let workspace: NSWorkspace

    init(
        pasteboard: NSPasteboard = .general,
        workspace: NSWorkspace = .shared
    ) {
        self.pasteboard = pasteboard
        self.workspace = workspace
    }

    var changeCount: Int {
        pasteboard.changeCount
    }

    var types: [NSPasteboard.PasteboardType] {
        pasteboard.types ?? []
    }

    func readFileURLs() -> [URL] {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [
            .urlReadingFileURLsOnly: true
        ]
        guard let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL] else {
            return []
        }
        return urls.filter(\.isFileURL)
    }

    func data(forType dataType: NSPasteboard.PasteboardType) -> Data? {
        pasteboard.data(forType: dataType)
    }

    func string(forType dataType: NSPasteboard.PasteboardType) -> String? {
        pasteboard.string(forType: dataType)
    }

    func frontmostSourceApp() -> ClipboardSourceApp? {
        guard let app = workspace.frontmostApplication else { return nil }
        return ClipboardSourceApp(
            bundleIdentifier: app.bundleIdentifier,
            localizedName: app.localizedName
        )
    }

    @discardableResult
    func write(_ payload: ClipboardPayload) -> Int {
        pasteboard.clearContents()

        switch payload {
        case .text(let text):
            pasteboard.setString(text, forType: .string)

        case .url(let url, let rawText):
            let stringToWrite = rawText.isEmpty ? url.absoluteString : rawText
            pasteboard.setString(stringToWrite, forType: .string)
            pasteboard.setString(url.absoluteString, forType: .URL)

        case .files(let urls):
            let nsURLs = urls.map { $0 as NSURL }
            pasteboard.writeObjects(nsURLs)

        case .image(let imagePayload):
            let data = imagePayload.tiffOrPngData
            if let bitmap = NSBitmapImageRep(data: data),
               let pngData = bitmap.representation(using: .png, properties: [:]) {
                pasteboard.setData(pngData, forType: .png)
                if let tiffData = bitmap.tiffRepresentation {
                    pasteboard.setData(tiffData, forType: .tiff)
                }
            } else {
                pasteboard.setData(data, forType: .png)
                pasteboard.setData(data, forType: .tiff)
            }
        }

        // Tag the pasteboard write with our internal marker so ClipboardMonitor
        // never re-captures self-restored items.
        pasteboard.setData(Data(), forType: PasteboardMarkerType.internalCaptureIgnore)
        return pasteboard.changeCount
    }
}
